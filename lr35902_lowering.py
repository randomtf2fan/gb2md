"""Instruction-family classifier for static LR35902-to-68000 lowering.

Families are intentionally semantic (LD_R_R, ADD_HL_RR, CB, etc.) rather than
one handler per byte. A 68000 backend therefore needs a few dozen lowerers,
not 256 unrelated opcode implementations.
"""
from __future__ import annotations

INVALID = {0xD3,0xDB,0xDD,0xE3,0xE4,0xEB,0xEC,0xED,0xF4,0xFC,0xFD}
DIRECT = {
 0x00:"NOP",0x08:"LD_A16_SP",0x10:"STOP",0x18:"JR",0x27:"DAA",0x2F:"CPL",0x37:"SCF",0x3F:"CCF",
 0x76:"HALT",0xC3:"JP",0xC9:"RET",0xCD:"CALL",0xD9:"RETI",0xE9:"JP_HL",0xF3:"DI",0xF9:"LD_SP_HL",0xFB:"EI",
 0xEA:"LD_A16_A",0xFA:"LD_A_A16",0xE0:"LDH_A8_A",0xF0:"LDH_A_A8",0xE2:"LDH_C_A",0xF2:"LDH_A_C",0xE8:"ADD_SP_R8",0xF8:"LD_HL_SP_R8",
}
def family(op):
    if op in INVALID:return "INVALID"
    if op == 0xCB:return "CB"
    if op in DIRECT:return DIRECT[op]
    if 0x40 <= op < 0x76 or 0x77 <= op < 0x80:return "LD_R_R"
    if 0x80 <= op < 0xC0:return ("ADD_A_R","ADC_A_R","SUB_A_R","SBC_A_R","AND_A_R","XOR_A_R","OR_A_R","CP_A_R")[(op>>3)&7]
    if op in (0x01,0x11,0x21,0x31):return "LD_RR_D16"
    if op in (0x02,0x12,0x22,0x32):return "LD_RR_A"
    if op in (0x0A,0x1A,0x2A,0x3A):return "LD_A_RR"
    if op in (0x03,0x13,0x23,0x33):return "INC_RR"
    if op in (0x0B,0x1B,0x2B,0x3B):return "DEC_RR"
    if op in (0x09,0x19,0x29,0x39):return "ADD_HL_RR"
    if op in (0x04,0x0C,0x14,0x1C,0x24,0x2C,0x34,0x3C):return "INC_R"
    if op in (0x05,0x0D,0x15,0x1D,0x25,0x2D,0x35,0x3D):return "DEC_R"
    if op in (0x06,0x0E,0x16,0x1E,0x26,0x2E,0x36,0x3E):return "LD_R_D8"
    if op in (0x07,0x0F,0x17,0x1F):return "ROT_A"
    if op in (0x20,0x28,0x30,0x38):return "JR_CC"
    if op in (0xC2,0xCA,0xD2,0xDA):return "JP_CC"
    if op in (0xC4,0xCC,0xD4,0xDC):return "CALL_CC"
    if op in (0xC0,0xC8,0xD0,0xD8):return "RET_CC"
    if op in (0xC1,0xD1,0xE1,0xF1):return "POP_RR"
    if op in (0xC5,0xD5,0xE5,0xF5):return "PUSH_RR"
    if op in (0xC6,0xCE,0xD6,0xDE,0xE6,0xEE,0xF6,0xFE):return ("ADD_A_D8","ADC_A_D8","SUB_A_D8","SBC_A_D8","AND_A_D8","XOR_A_D8","OR_A_D8","CP_A_D8")[(op>>3)&7]
    if op in (0xC7,0xCF,0xD7,0xDF,0xE7,0xEF,0xF7,0xFF):return "RST"
    return "UNCLASSIFIED"
